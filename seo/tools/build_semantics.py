def src_of(q):
    s = []
    v = SUG.get(q, '')
    if 'yandex' in v: s.append('Я-подсказка (Астана)')
    if 'google' in v: s.append('G-подсказка (KZ)')
    if q in GREL: s.append('Google.kz «Другие также ищут»')
    if q in KZ: s.append('Wordstat KZ')
    if q in RU: s.append('keys.so (РФ)')
    if q in KZ_TAIL: s.append('Wordstat KZ (хвост)')
    return ', '.join(s) or 'гипотеза'

